export function resolveStrings(overrides: Partial<FlowStrings> | undefined): FlowStrings {
  if (!overrides) return DEFAULT_STRINGS;
  const result = { ...DEFAULT_STRINGS };
  for (const key of Object.keys(overrides) as Array<keyof FlowStrings>) {
    const value = overrides[key];
    if (value !== undefined) result[key] = value;
  }
  return result;
}

/** Fills `{name}` placeholders. */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
