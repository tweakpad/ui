import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const catalogSource = await readFile(join(root, 'src/catalog.ts'), 'utf8');
const entries = [...catalogSource.matchAll(/\['([^']+)',\s*'(tp-[^']+)',\s*'[^']+'\]/g)].map(
  ([, name, tagName]) => ({ name, tagName }),
);

if (entries.length !== 62) {
  throw new Error(`Expected 62 catalog entries, found ${entries.length}`);
}

const outputDirectory = join(root, 'src/stories/generated');
const authoredStories = new Set([
  'tp-accordion',
  'tp-button',
  'tp-button-group',
  'tp-collapsible',
  'tp-icon',
]);
await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });

for (const { name, tagName } of entries) {
  if (authoredStories.has(tagName)) continue;
  const filename = `${tagName.slice(3)}.stories.ts`;
  const source = `// Generated by scripts/generate-component-stories.mjs.\nimport type { Meta, StoryObj } from '@storybook/web-components-vite';\nimport { renderComponentExample } from '../examples.js';\n\nconst meta = {\n  title: 'Components/${name}',\n  component: '${tagName}',\n  tags: ['autodocs'],\n  parameters: { layout: 'padded' },\n  render: () => renderComponentExample('${tagName}'),\n} satisfies Meta;\n\nexport default meta;\ntype Story = StoryObj<typeof meta>;\n\nexport const Default: Story = {};\n`;
  await writeFile(join(outputDirectory, filename), source);
}

console.log(
  JSON.stringify({ generatedStories: entries.length - authoredStories.size, outputDirectory }),
);
